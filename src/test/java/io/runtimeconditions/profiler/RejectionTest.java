package io.runtimeconditions.profiler;

import static io.runtimeconditions.profiler.TestSupport.generate;
import static io.runtimeconditions.profiler.TestSupport.packages;
import static io.runtimeconditions.profiler.TestSupport.workload;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import io.runtimeconditions.profiler.TestSupport.Result;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;

class RejectionTest {
    private static final String OWNED = "owned-kind-interface";
    private static final String TRANSITIVE = "transitive-closure,transitive-closure-middle,transitive-closure-leaf";

    @ParameterizedTest(name = "{0} is rejected with no output")
    @CsvSource(delimiter = '|', value = {
            "dynamic|owned-kind-interface|error: extract: src/main/java/w/W.java:12:61: this value cannot be determined statically",
            "wrong-kind|owned-kind-interface,transitive-closure,transitive-closure-middle,transitive-closure-leaf|error: extract: src/main/java/w/W.java:7:52: Command is not a field of the service declaration",
            "no-interface|owned-kind-interface|error: extract: src/main/java/w/W.java:7:35: the service declaration has no interface",
            "missing-required|owned-kind-interface|error: extract: src/main/java/w/W.java:8:61: Http is missing the required field endpoint",
            "not-generated|owned-kind-interface|error: extract: src/main/java/w/W.java:6:52: only types generated by a binding package on the classpath can be constructed",
            "schema-violation|owned-kind-interface|error: schema: condition 1 (service) does not satisfy https://runtimeconditions.io/conformance/owned-kind-interface:1.0.0#schema:service-http: $: required property 'region' not found",
    })
    void rejected(String workload, String packages, String message) {
        Result result = generate(workload(workload), packages(packages.split(",")), workload);
        assertEquals(1, result.code());
        assertEquals("", result.out());
        assertEquals(message, result.err().trim());
    }

    @ParameterizedTest(name = "{0}")
    @CsvSource(delimiter = '|', value = {
            "the conflicting extensions of the same kind and interface|owned-kind-interface,scoped-domains-collisions",
    })
    void aSchemaFromEveryUsedExtensionAppliesToACondition(String name, String packages) {
        // owned-kind-interface and scoped-domains-collisions both define a service with an http interface, and their schemas
        // disagree. A workload that declares against both must satisfy both, so this one cannot.
        Result result = generate(workload("both-service-extensions"), packages(packages.split(",")), "both");
        assertEquals(1, result.code(), name);
        assertEquals("", result.out());
        assertTrue(result.err().contains("does not satisfy"), result.err());
    }
}
