package io.runtimeconditions.profiler;

import static io.runtimeconditions.profiler.TestSupport.both;
import static io.runtimeconditions.profiler.TestSupport.generate;
import static io.runtimeconditions.profiler.TestSupport.workload;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import io.runtimeconditions.profiler.TestSupport.Result;
import java.util.regex.Pattern;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;

class RejectionTest {
    @ParameterizedTest(name = "{0} is rejected with no output")
    @CsvSource(delimiter = '|', value = {
            "dynamic|error: extract: src/main/java/app/App.java:12:64: this value cannot be determined statically",
            "wrong-kind|error: extract: src/main/java/app/App.java:8:54: KeyValue is not a field of the datastore declaration",
            "no-interface|error: extract: src/main/java/app/App.java:7:36: the cache declaration has no interface",
            "missing-required|error: extract: src/main/java/app/App.java:14:128: KeyValueConfigurationEnvItem is missing the required field property",
            "not-generated|error: extract: src/main/java/app/App.java:6:51: only types generated by a binding package on the classpath can be constructed",
    })
    void rejected(String workload, String message) {
        Result result = generate(workload(workload), both(), workload);
        assertEquals(1, result.code());
        assertEquals("", result.out());
        assertTrue(Pattern.compile(Pattern.quote(message)).matcher(result.err().trim()).find(), "got: " + result.err());
    }
}
